#!/usr/bin/env python3
"""Plot Hermite scaling curves versus P for d_sweep_hermite experiments.

This script mirrors the P-scan analysis workflow used for the erf experiments,
but replaces the theory branch with the Hermite continuation solver from
lib/hermite_activation_solvers.py and replaces the empirical quantities with
projection variances of the second hidden layer preactivations onto He1/He3.

For each run it computes:
  - H11_emp: variance of <h_k(x), He1(x_0)> across neuron/seed index
  - H33_emp: variance of <h_k(x), He3(x_0)> across neuron/seed index
  - lambda_sigma_emp: top eigenvalue of the readin covariance (W0)

Theoretical curves are generated by solving the Hermite fixed-point system
over a log-P interval covering the observed experiments.
"""

